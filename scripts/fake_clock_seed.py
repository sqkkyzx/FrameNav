"""Seed the Phase 1 test clock from the build host's UTC, without Wi-Fi.

Copyright 2026 FrameNav contributors
SPDX-License-Identifier: Apache-2.0

This is approximate time: build/upload delay is not compensated, and rebooting
reuses the embedded seed. It is NOT a persistent or synchronized RTC.
Only the small clock translation unit includes the generated header.
"""

from datetime import datetime, timezone
from pathlib import Path

Import("env")

epoch = int(datetime.now(timezone.utc).timestamp())
seed = datetime.fromtimestamp(epoch, timezone.utc).isoformat()
header = Path(env.subst("$PROJECT_INCLUDE_DIR")) / "fake_clock_seed.generated.h"
header.write_text(
    "/* Generated by PlatformIO; do not edit or commit. */\n"
    "/* SPDX-License-Identifier: Apache-2.0 */\n"
    "#ifndef ALPHALOC_FAKE_CLOCK_SEED_GENERATED_H\n"
    "#define ALPHALOC_FAKE_CLOCK_SEED_GENERATED_H\n"
    f"#define ALPHALOC_FAKE_GPS_EPOCH {epoch}LL\n"
    f"/* Build-host UTC: {seed} */\n"
    "#endif\n",
    encoding="utf-8",
)
print(f"Phase 1 stepping-clock seed: {seed} (approximate; resets on boot)")
